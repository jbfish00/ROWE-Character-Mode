#!/usr/bin/env python3
"""Import staged donor OVERWORLD sheets and BATTLE BACK PICS for Character Mode.

The counterpart to `import_donor_front_pics.py`, for the other two asset slots.
Until this existed, `sprites/donors/` was readable by exactly one tool and that
tool did front pics alone -- so 27 overworld sheets and 6 back pics sat staged
and unreachable while PLAN.md called the slots "art-blocked". They were not.

`import_sprites.py` built the first 95 overworld sheets, but it resolves its
donors from a scratchpad checkout that no longer exists, so it cannot be re-run.
This script reads `sprites/donors/` instead and writes into its OWN marker
blocks (`donor-ow-*`, `donor-back-*`), a separate namespace from
import_sprites.py's, so the two never fight over the same text.

⚠️ THE OVERWORLD SLOT IS NOT A ONE-LINE ALIAS FIX. `emit_characters.py` accepts
an `OBJ_EVENT_GFX_*` id for the player avatar only if it is listed in
`imported_ow.txt` / `imported_ow_donor.txt` or ends in `_NORMAL`. That gate is
deliberate: the player avatar drives the 24-entry `BrendanMayNormal` animation
table, whose walk/run anims reference frames 0-17, while a plain NPC id ships a
SHORT pic table and reads past its end -- a crash, not a glitch. Birch, Anabel,
Brandon, Greta, Lucy, Noland, Spenser and Tucker all already have an
`OBJ_EVENT_GFX_*` constant and wiring it would look like a free win; it ships a
crash. Every id this script emits is a real 18-frame player-grade sheet built by
`import_sprites.build_ow_sheet()`, and only those ids are added to the allowlist.

IDEMPOTENCY, and why it is load-bearing (see `import_donor_front_pics.mine()`):
every marker block is REWRITTEN WHOLESALE, so a character absent from this run's
picks is not "left alone", it is DELETED. The front-pic importer shipped that
bug for months and destroyed 99 imports the first time it ran with real work to
do. So this script re-derives its WHOLE output on every run: previously-imported
characters are re-picked from staged art, their ids are HELD FIXED, and it
REFUSES TO RUN (exit 1, nothing written) if any previously-imported character
stops resolving to staged art.

Emits, per overworld character:
    graphics/object_events/pics/people/<snake>.png   18-frame 16x576 sheet
    graphics/object_events/pics/people/<snake>.pal   JASC palette (CRLF)
    include/constants/event_objects.h                OBJ_EVENT_GFX_CM_<KEY>
    src/data/object_events/object_event_graphics.h   INCBINs
    .../object_event_pic_tables.h                    18-entry pic table
    .../object_event_graphics_info.h                 graphics info struct
    .../object_event_graphics_info_pointers.h        pointer row
    src/event_object_movement.c                      palette tag + registration
    include/graphics.h                               externs
    tools/character_mode/imported_ow_donor.txt       the player-safe allowlist

and per back-pic character:
    graphics/trainers/back_pics/<snake>_back_pic.png 4- or 5-frame 64xN
    graphics/trainers/palettes/<snake>_back.pal      JASC palette (CRLF)
    include/constants/trainers.h                     TRAINER_BACK_PIC_CM_<KEY>
    src/data/graphics/trainers.h                     INCBINs
    include/graphics.h, include/data.h               externs
    src/data/trainer_graphics/back_pic_tables.h      coords + pal + sheet rows
    src/data/trainer_graphics/back_pic_anims.h       anim arrays + ptr rows
    src/data.c                                       SpriteFrameImage tables
    src/pokemon.c                                    sprite template

⚠️ TWO OF THOSE ARRAYS ARE POSITIONAL, NOT DESIGNATED:
`gTrainerBackPicTable` (back_pic_tables.h) and
`gSpriteTemplateTable_TrainerBackSprites` (pokemon.c) are indexed by back-pic id
with no `[id] =` on the rows, so entries MUST be appended in id order at the end
of the array. Both blocks are emitted sorted by id for exactly that reason.

Usage:  python3 tools/character_mode/import_donor_ow_backs.py [--dry-run]
Then:   python3 tools/character_mode/emit_characters.py && make -j
"""
