def _strip(text, tag):
    return re.sub(re.escape(MS.format(tag=tag)) + r".*?"
                  + re.escape(ME.format(tag=tag)) + r"\n?", "", text, flags=re.S)


def _block(path, tag, block, anchor_re, before=True):
    """Insert/replace a marker block at a WHOLE-LINE boundary.

    ⚠️ `import_sprites._block` prepends a "\\n" for the after-anchor case and
    strips only `MS…ME\\n?`, so every re-run leaves one more blank line behind
    and the file is not byte-stable. Anchoring past the anchor line's own
    newline instead makes a re-run reproduce the file exactly -- which is what
    lets "run it twice and diff" be a real idempotency test rather than a
    hopeful one.
    """
    text = _strip(read(path), tag)
    wrapped = "%s\n%s\n%s\n" % (MS.format(tag=tag), block.rstrip("\n"),
                                ME.format(tag=tag))
    m = list(re.finditer(anchor_re, text, re.M))
    assert m, (path, anchor_re)
    if before:
        pos = m[-1].start()
    else:
        nl = text.find("\n", m[-1].end())
        pos = len(text) if nl < 0 else nl + 1
    write(path, text[:pos] + wrapped + text[pos:])


def _block_in_array(path, tag, block, array_re):
    """Append inside a named array's braces (before its closing `};`).

    Needed wherever a bare `^};` anchor would pick the file's LAST array --
    import_sprites.py records losing entries into `gMauvilleOldManGraphicsInfo
    Pointers` that way, which made the lookup return NULL and crashed the player
    avatar.
    """
    text = _strip(read(path), tag)
    m = re.search(array_re, text)
    assert m, (path, array_re)
    close = text.index("\n};", m.end()) + 1
    write(path, text[:close] + "%s\n%s%s\n"
          % (MS.format(tag=tag), block, ME.format(tag=tag)) + text[close:])


def previous_report():
    """{(kind, display name): (source, files)} from the last run's report.

    ⚠️ "Refuses to run when a character stops resolving" does NOT cover the case
    where a character stops resolving TO THE SAME ART. Hiding
    `rogue/oak_ow.png` leaves `taar/oak_ow.png` standing, so the refusal never
    fires, the run reports "0 new" -- and Oak's overworld sprite has silently
    become a different artist's drawing. That was found by negative control, not
    by reasoning. A source change is legitimate (re-preferencing, a better
    sprite staged) so it is not fatal, but it is never silent.
    """
    path = os.path.join(HERE, "donor_ow_backs.txt")
    if not os.path.isfile(path):
        return {}
    out, rows = {}, 0
    for line in read(path).splitlines():
        if line.startswith("#") or not line.strip():
            continue
        rows += 1
        m = re.match(r"(ow|back)\s+(.+?)\s{2,}(\S+)\s{2,}(\S.*?)\s{2,}", line)
        if m:
            out[(m.group(1), m.group(2).strip())] = (m.group(3), m.group(4).strip())
    # ⚠️ A parser that quietly matches nothing is a check that cannot fail, and
    # this one already was one: the first regex wanted exactly three spaces after
    # the kind, which "ow   " has and "back " does not -- so drift detection was
    # blind to every back pic and said so by staying silent.
    assert len(out) == rows, (
        "donor_ow_backs.txt: parsed %d of %d rows -- the report format and this "
        "parser have drifted, and drift detection is now partly blind"
        % (len(out), rows))
    return out


def mine_ow(header):
    """{KEY: offset} for the OW ids THIS script emitted on a previous run."""
    m = re.search(re.escape(MS.format(tag="donor-ow-ids")) + r"(.*?)"
                  + re.escape(ME.format(tag="donor-ow-ids")), header, re.S)
    if not m:
        return {}
    return {k: int(v) for k, v in re.findall(
        r"#define OBJ_EVENT_GFX_CM_(\w+)\s+\(OBJ_EVENT_GFX_CHARMODE_LAST \+ (\d+)\)",
        m.group(1))}


def mine_back(header):
    """{KEY: id} for the back-pic ids THIS script emitted on a previous run."""
    m = re.search(re.escape(MS.format(tag="donor-back-ids")) + r"(.*?)"
                  + re.escape(ME.format(tag="donor-back-ids")), header, re.S)
    if not m:
        return {}
    return {k: int(v) for k, v in
            re.findall(r"#define TRAINER_BACK_PIC_CM_(\w+)\s+(\d+)", m.group(1))}


def main():
    dry = "--dry-run" in sys.argv
    ev_path = os.path.join(TARGET, "include/constants/event_objects.h")
    tr_path = os.path.join(TARGET, "include/constants/trainers.h")
    ev_h, tr_h = read(ev_path), read(tr_path)

    obj_gfx = set(re.findall(r"#define (OBJ_EVENT_GFX_\w+)", ev_h))
    back_pics = set(re.findall(r"#define (TRAINER_BACK_PIC_\w+)", tr_h))
    ours_ow, ours_back = mine_ow(ev_h), mine_back(tr_h)

    # Player-safe overworld ids from the OTHER importer, plus ROWE's own player
    # costumes (the `_NORMAL` ids, handled in the loop below).
    #
    # ⚠️ `imported_ow_donor.txt` is deliberately NOT read here. It is THIS
    # script's own output, and treating your own previous output as "somebody
    # else already covered this character" is the exact conflation that made the
    # front-pic importer delete 99 imports. Subtracting only what the marker
    # block still lists is not enough either: if the block and the txt ever
    # disagree, the txt silently wins and the character is skipped instead of
    # re-emitted. So the txt is informational only, and the block is the record.
    p = os.path.join(HERE, "imported_ow.txt")
    safe_ow = ({t for t in read(p).split() if t.startswith("OBJ_EVENT_GFX_")}
               if os.path.isfile(p) else set())
    safe_ow -= {"OBJ_EVENT_GFX_CM_" + k for k in ours_ow}
    back_pics -= {"TRAINER_BACK_PIC_CM_" + k for k in ours_back}

    ow_picks, back_picks = [], []
    ow_skip = ow_missing = back_skip = back_missing = 0
    lost = []
    for disp in display_names():
        key = key_of(disp)
        # --- overworld
        if any(c in obj_gfx and (c in safe_ow or c.endswith("_NORMAL"))
               for c in const_candidates(disp, "OBJ_EVENT_GFX_")):
            ow_skip += 1
        else:
            c = ow_candidates(disp)
            if c:
                src, pngs, fw, n = c[0]
                ow_picks.append(dict(disp=disp, key=key, src=src, pngs=pngs,
                                     fw=fw, frames=n,
                                     snake="cm_donor_" + slug(disp)))
            elif key in ours_ow:
                lost.append("overworld: " + disp)
            else:
                ow_missing += 1
        # --- back pic
        if any(c in back_pics for c in const_candidates(disp, "TRAINER_BACK_PIC_")):
            back_skip += 1
            continue
        c = back_candidates(disp)
        if c:
            src, png, n = c[0]
            back_picks.append(dict(disp=disp, key=key, src=src, png=png,
                                   frames=n,
                                   snake="cm_donor_" + slug(disp)))
        elif key in ours_back:
            lost.append("back pic: " + disp)
        else:
            back_missing += 1

    if lost:
        sys.exit("REFUSING TO RUN -- %d asset(s) imported by a previous run no "
                 "longer resolve to any staged donor art:\n  %s\n"
                 "Every marker block is rewritten wholesale, so re-running now "
                 "would DELETE their defines, INCBINs and table rows while "
                 "leaving the ROM referencing them. Restore the staged art (or "
                 "remove them from the donor-* blocks deliberately) first."
                 % (len(lost), "\n  ".join(lost)))

    for p in ow_picks:
        c = "OBJ_EVENT_GFX_CM_" + p["key"]
        if c in obj_gfx and p["key"] not in ours_ow:
            sys.exit("id collision: %s already exists (character %s)" % (c, p["disp"]))

    prev = previous_report()
    drift = []
    for kind, picks in (("ow", ow_picks), ("back", back_picks)):
        for p in picks:
            was = prev.get((kind, p["disp"]))
            now = (p["src"], " + ".join(os.path.basename(x) for x in
                                        (p["pngs"] if kind == "ow" else [p["png"]])))
            if was and was != now:
                drift.append("%-5s %-24s %s/%s  ->  %s/%s"
                             % (kind, p["disp"], was[0], was[1], now[0], now[1]))

    fresh_ow = [p for p in ow_picks if p["key"] not in ours_ow]
    fresh_back = [p for p in back_picks if p["key"] not in ours_back]
    print("overworld: %d already covered, %d to emit (%d new), %d have no staged art"
          % (ow_skip, len(ow_picks), len(fresh_ow), ow_missing))
    print("back pics: %d already covered, %d to emit (%d new), %d have no staged art"
          % (back_skip, len(back_picks), len(fresh_back), back_missing))
    for label, picks in (("overworld", fresh_ow), ("back", fresh_back)):
        by_src = {}
        for p in picks:
            by_src[p["src"]] = by_src.get(p["src"], 0) + 1
        for s in PREFERENCE:
            if by_src.get(s):
                print("   new %-9s from %-12s %d" % (label, s, by_src[s]))
    if drift:
        print("\n⚠️  %d already-imported asset(s) now resolve to DIFFERENT art "
              "(the id is held, the picture is not):" % len(drift))
        for d in drift:
            print("   " + d)
    if dry:
        return 0
    if not ow_picks and not back_picks:
        print("nothing to do")
        return 0

    # --- ids: held fixed for anything we issued before, appended after the max
    nxt = max(list(ours_ow.values()) + [0]) + 1
    for p in ow_picks:
        if p["key"] in ours_ow:
            p["off"] = ours_ow[p["key"]]
        else:
            p["off"] = nxt
            nxt += 1
    stock_back = [int(m) for m in re.findall(
        r"#define TRAINER_BACK_PIC_\w+\s+(\d+)", tr_h)]
    nxt = max(stock_back + list(ours_back.values())) + 1
    for p in back_picks:
        if p["key"] in ours_back:
            p["id"] = ours_back[p["key"]]
        else:
            p["id"] = nxt
            nxt += 1
    back_by_id = sorted(back_picks, key=lambda p: p["id"])

    # --- art ---------------------------------------------------------------
    ow_dir = os.path.join(TARGET, "graphics/object_events/pics/people")
    bp_dir = os.path.join(TARGET, "graphics/trainers/back_pics")
    pal_dir = os.path.join(TARGET, "graphics/trainers/palettes")
    for p in ow_picks:
        img = build_player_sheet(p["pngs"], p["fw"],
                                 os.path.join(ow_dir, p["snake"] + ".png"))
        png_to_jasc(img, os.path.join(ow_dir, p["snake"] + ".pal"))
    for p in back_picks:
        img, n = build_back_pic(p["png"],
                                os.path.join(bp_dir, p["snake"] + "_back_pic.png"))
        assert n == p["frames"], (p["disp"], n, p["frames"])
        png_to_jasc(img, os.path.join(pal_dir, p["snake"] + "_back.pal"))

    if ow_picks:
        emit_ow(ow_picks, ev_path)
    if back_picks:
        emit_back(back_picks, back_by_id, tr_path)

    write(os.path.join(HERE, "imported_ow_donor.txt"),
          "# Player-grade 18-frame overworld sheets emitted by\n"
          "# tools/character_mode/import_donor_ow_backs.py. emit_characters.py\n"
          "# only accepts an OBJ_EVENT_GFX id as the player avatar if it is\n"
          "# listed here (or in imported_ow.txt, or ends in _NORMAL).\n"
          + "".join("OBJ_EVENT_GFX_CM_%s\n" % p["key"] for p in ow_picks))
    write(os.path.join(HERE, "donor_ow_backs.txt"),
          "# Overworld sheets and back pics imported from sprites/donors/ by\n"
          "# tools/character_mode/import_donor_ow_backs.py -- regenerate, do not edit.\n"
          + "".join("ow   %-24s %-10s %-42s %2d frames of %dx32\n"
                    % (p["disp"], p["src"],
                       " + ".join(os.path.basename(x) for x in p["pngs"]),
                       p["frames"], p["fw"])
                    for p in ow_picks)
          + "".join("back %-24s %-10s %-32s %2d frames\n"
                    % (p["disp"], p["src"], os.path.basename(p["png"]), p["frames"])
                    for p in back_by_id))
    print("emitted %d overworld sheets (%d new) and %d back pics (%d new)"
          % (len(ow_picks), len(fresh_ow), len(back_picks), len(fresh_back)))
    print("next: python3 tools/character_mode/emit_characters.py && make -j")
    return 0


def emit_ow(picks, ev_path):
    # --- ids. Expressed relative to OBJ_EVENT_GFX_CHARMODE_LAST so that
    # import_sprites.py's block stays the sole owner of the base, and
    # NUM_OBJ_EVENT_GFX is repointed at ours (it sizes
    # gObjectEventGraphicsInfoPointers and bounds the lookup in
    # event_object_movement.c:3765 -- leaving it at CHARMODE_LAST would make
    # every id below refuse to load).
    lines = ["#define OBJ_EVENT_GFX_CM_%s%s(OBJ_EVENT_GFX_CHARMODE_LAST + %d)"
             % (p["key"], " " * max(1, 20 - len(p["key"])), p["off"]) for p in picks]
    lines.append("#define OBJ_EVENT_GFX_CHARMODE_DONOR_LAST OBJ_EVENT_GFX_CM_%s"
                 % max(picks, key=lambda p: p["off"])["key"])
    _block(ev_path, "donor-ow-ids", "\n".join(lines),
           r"^#define NUM_OBJ_EVENT_GFX", before=True)
    text = read(ev_path)
    text, n = re.subn(r"^#define NUM_OBJ_EVENT_GFX(\s+)\(OBJ_EVENT_GFX_\w+ \+ 1\)",
                      r"#define NUM_OBJ_EVENT_GFX\1(OBJ_EVENT_GFX_CHARMODE_DONOR_LAST + 1)",
                      text, flags=re.M)
    assert n == 1, "NUM_OBJ_EVENT_GFX not found exactly once (%d)" % n
    write(ev_path, text)

    _block(os.path.join(TARGET, "src/data/object_events/object_event_graphics.h"),
           "donor-ow-incbins", "".join(
               'const u32 gObjectEventPic_Cm%s[] = INCBIN_U32("graphics/object_events/pics/people/%s.4bpp");\n'
               'const u16 gObjectEventPalette_Cm%s[] = INCBIN_U16("graphics/object_events/pics/people/%s.gbapal");\n'
               % (camel(p["key"]), p["snake"], camel(p["key"]), p["snake"])
               for p in picks), r"\Z", before=True)

    _block(os.path.join(TARGET, "src/data/object_events/object_event_pic_tables.h"),
           "donor-ow-pics", "".join(
               "static const struct SpriteFrameImage gObjectEventPicTable_Cm%s[] = {\n%s};\n"
               % (camel(p["key"]),
                  "".join("    overworld_frame(gObjectEventPic_Cm%s, %d, 4, %d),\n"
                          % (camel(p["key"]), p["fw"] // 8, i)
                          for i in range(NUM_PLAYER_FRAMES)))
               for p in picks), r"\Z", before=True)

    # .size is the BYTE size of one frame (fw * 32 / 2 at 4bpp) and the OAM
    # tables are per frame width -- a 32px sheet described as 16px reads half a
    # frame per slot and walks off the end of the pic table.
    _block(os.path.join(TARGET, "src/data/object_events/object_event_graphics_info.h"),
           "donor-ow-info", "".join(
               "const struct ObjectEventGraphicsInfo gObjectEventGraphicsInfo_Cm%s = "
               "{0xFFFF, OBJ_EVENT_PAL_CM_%s, OBJ_EVENT_PAL_TAG_NONE, %d, %d, 32, 5, "
               "SHADOW_SIZE_M, FALSE, FALSE, TRACKS_FOOT, &gObjectEventBaseOam_%dx32, "
               "gObjectEventSpriteOamTables_%dx32, gObjectEventImageAnimTable_BrendanMayNormal, "
               "gObjectEventPicTable_Cm%s, gDummySpriteAffineAnimTable};\n"
               % (camel(p["key"]), p["key"], p["fw"] * 32 // 2, p["fw"],
                  p["fw"], p["fw"], camel(p["key"])) for p in picks),
           r"\Z", before=True)

    _block_in_array(
        os.path.join(TARGET, "src/data/object_events/object_event_graphics_info_pointers.h"),
        "donor-ow-ptrs",
        "".join("    [OBJ_EVENT_GFX_CM_%s] = &gObjectEventGraphicsInfo_Cm%s,\n"
                % (p["key"], camel(p["key"])) for p in picks),
        r"gObjectEventGraphicsInfoPointers\[[^\]]*\]\s*=\s*\{")

    mv = os.path.join(TARGET, "src/event_object_movement.c")
    _block(mv, "donor-ow-paltags", "".join(
        "#define OBJ_EVENT_PAL_CM_%s%s0x%04X\n"
        % (p["key"], " " * max(1, 18 - len(p["key"])), PAL_TAG_BASE + p["off"] - 1)
        for p in picks), r"^// CHARMODE-SPRITES-END pal-tags$", before=False)
    _block(mv, "donor-ow-palentries", "".join(
        "    {gObjectEventPalette_Cm%s, OBJ_EVENT_PAL_CM_%s},\n"
        % (camel(p["key"]), p["key"]) for p in picks),
        r"^\s*\{gObjectEventPalette_Steven,", before=True)

    _block(os.path.join(TARGET, "include/graphics.h"), "donor-ow-externs",
           "".join("extern const u32 gObjectEventPic_Cm%s[];\n"
                   "extern const u16 gObjectEventPalette_Cm%s[];\n"
                   % (camel(p["key"]), camel(p["key"])) for p in picks),
           r"^#endif", before=True)


def emit_back(picks, by_id, tr_path):
    _block(tr_path, "donor-back-ids", "\n".join(
        "#define TRAINER_BACK_PIC_CM_%s%s%d"
        % (p["key"], " " * max(1, 17 - len(p["key"])), p["id"]) for p in by_id),
        r"^// CHARMODE-SPRITES-END back-ids$", before=False)

    _block(os.path.join(TARGET, "src/data/graphics/trainers.h"), "donor-back-incbins",
           "".join(
               'const u8 gTrainerBackPic_Cm%s[] = INCBIN_U8("graphics/trainers/back_pics/%s_back_pic.4bpp");\n'
               'const u16 gTrainerBackPicPalette_Cm%s[] = INCBIN_U16("graphics/trainers/palettes/%s_back.gbapal");\n'
               % (camel(p["key"]), p["snake"], camel(p["key"]), p["snake"])
               for p in picks), r"\Z", before=True)

    _block(os.path.join(TARGET, "include/graphics.h"), "donor-back-externs",
           "".join("extern const u8 gTrainerBackPic_Cm%s[];\n"
                   "extern const u16 gTrainerBackPicPalette_Cm%s[];\n"
                   % (camel(p["key"]), camel(p["key"])) for p in picks),
           r"^#endif", before=True)
    _block(os.path.join(TARGET, "include/data.h"), "donor-back-frame-externs",
           "".join("extern const struct SpriteFrameImage gTrainerBackPicTable_Cm%s[];\n"
                   % camel(p["key"]) for p in picks),
           r"^// CHARMODE-SPRITES-END back-frame-externs$", before=False)

    bt = os.path.join(TARGET, "src/data/trainer_graphics/back_pic_tables.h")
    # coords + palettes are designated-initializer arrays, so row order is free;
    # gTrainerBackPicTable is NOT, so it is appended in id order at the end.
    _block(bt, "donor-back-coords", "".join(
        "    [TRAINER_BACK_PIC_CM_%s] = {.size = 8, .y_offset = %d},\n"
        % (p["key"], 5 if p["frames"] == 5 else 4) for p in picks),
        r"^// CHARMODE-SPRITES-END back-coords$", before=False)
    _block(bt, "donor-back-pals", "".join(
        "    TRAINER_BACK_PAL(CM_%s, gTrainerBackPicPalette_Cm%s),\n"
        % (p["key"], camel(p["key"])) for p in picks),
        r"^// CHARMODE-SPRITES-END back-pals$", before=False)
    _block_in_array(bt, "donor-back-sheets", "".join(
        "    (const u32 *)gTrainerBackPic_Cm%s, 0x%04X, TRAINER_BACK_PIC_CM_%s,\n"
        % (camel(p["key"]), p["frames"] * 0x800, p["key"]) for p in by_id),
        r"gTrainerBackPicTable\[\]\s*=\s*\{")

    # 4-frame donors play the Emerald throw (gAnimCmd_May_Steven_1, frames
    # 0,1,2,0,3); 5-frame donors play the FRLG one (gAnimCmd_Red_1, frames
    # 1,2,3,4,0). Both are static in this same file, defined above the block.
    ba = os.path.join(TARGET, "src/data/trainer_graphics/back_pic_anims.h")
    _block(ba, "donor-back-anims", "".join(
        "static const union AnimCmd *const sBackAnims_Cm%s[] =\n{\n"
        "    %s,\n    %s,\n};\n"
        % (camel(p["key"]),
           "sAnim_GeneralFrame0" if p["frames"] == 5 else "sAnim_GeneralFrame3",
           "gAnimCmd_Red_1" if p["frames"] == 5 else "gAnimCmd_May_Steven_1")
        for p in picks),
        r"^const union AnimCmd \*const \*const gTrainerBackAnimsPtrTable", before=True)
    _block(ba, "donor-back-anim-ptrs", "".join(
        "    [TRAINER_BACK_PIC_CM_%s] = sBackAnims_Cm%s,\n"
        % (p["key"], camel(p["key"])) for p in picks),
        r"^// CHARMODE-SPRITES-END back-anim-ptrs$", before=False)

    _block(os.path.join(TARGET, "src/data.c"), "donor-back-frameimgs", "".join(
        "const struct SpriteFrameImage gTrainerBackPicTable_Cm%s[] =\n{\n%s};\n"
        % (camel(p["key"]),
           "".join("    gTrainerBackPic_Cm%s%s, 0x0800,\n"
                   % (camel(p["key"]), "" if i == 0 else " + 0x%04X" % (i * 0x800))
                   for i in range(p["frames"])))
        for p in picks),
        r"^// CHARMODE-SPRITES-END back-frameimgs$", before=False)

    # gSpriteTemplateTable_TrainerBackSprites is indexed by back-pic id with no
    # designators, so these rows MUST be last and in id order.
    _block_in_array(os.path.join(TARGET, "src/pokemon.c"), "donor-back-templates",
                    "".join("    {\n        .tileTag = 0xFFFF,\n        .paletteTag = 0,\n"
                            "        .oam = &gOamData_831ACB0,\n        .anims = NULL,\n"
                            "        .images = gTrainerBackPicTable_Cm%s,\n"
                            "        .affineAnims = gUnknown_082FF618,\n"
                            "        .callback = sub_8039BB4,\n    },\n" % camel(p["key"])
                            for p in by_id),
                    r"gSpriteTemplateTable_TrainerBackSprites\[\]\s*=\s*\{")


if __name__ == "__main__":
    sys.exit(main())
