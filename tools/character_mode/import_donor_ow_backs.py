# Our own marker namespace. import_sprites.py's blocks say "generated by
# tools/character_mode/import_sprites.py" in the START line, so the two never
# match each other's delete regex even where the tag names rhyme.
MS = "// CHARMODE-SPRITES-START {tag} (generated by tools/character_mode/import_donor_ow_backs.py)"
ME = "// CHARMODE-SPRITES-END {tag}"

# Best source first -- the same order and the same reasoning as
# `import_donor_front_pics.PREFERENCE`, extended with the three sets that only
# hold overworld/back art. Ordering below `hns` is by STRENGTH OF ATTRIBUTION,
# weakest last.
#
# ⚠️ A DIRECTORY NOT NAMED HERE IS SILENTLY IGNORED -- `candidates()` iterates
# this list, not `os.listdir(DONORS)`, so staging art into a new set without
# adding it here looks exactly like "there is no art for that character".
#
#   ashgray      front pics only, kept for order parity with the front importer
#   rogue        largest coherent set, one consistent style
#   taar         per-author attribution recoverable, explicit free-to-use grant
#   taar_gap     same repo, the 2026-07-28 gap-fill pass; per-file ARTIST named
#                in its CREDITS.txt, which is stronger than plain `taar/`
#   hns          project-level credit, no per-file artist
#   kalarie      named author, explicit grant; the only anime OW art anywhere
#   greenphx     named author, explicit (if optional) grant
#   pokesho      archived, permission inferred
#   dollsteak    thread-wide grant from the thread owner, not the contributor
#   loulilie     named author
#   platinum     no per-sprite credit at all, but one coherent project
#   unattributed NO licence, NO artist, NO project identity -- deliberately last
PREFERENCE = ["ashgray", "rogue", "taar", "taar_gap", "hns", "kalarie",
              "greenphx", "pokesho", "pokesho_field", "dollsteak", "loulilie",
              "platinum", "unattributed"]

# Display name -> donor filename stem, when they differ. Deliberately NOT
# shared with the front importer's ALIAS: there, James resolves to the Ash Gray
# `jessie_james` DUO portrait; here he has a solo overworld sheet of his own.
ALIAS = {}

# Back-pic donors that are not already 4 or 5 frames of 64x64. The value is the
# frame indices to take, in order, and the reason -- a judgement call about
# somebody's animation, so it is written down rather than guessed at.
BACK_FRAME_PICK = {
    # yoshord's Lance is a six-frame sheet with one extra intermediate raise
    # (frame 3) between "hand up" and "throw". Dropping it yields exactly the
    # FRLG five-frame pattern gAnimCmd_Red_1 plays: idle, hand low, hand up,
    # throw, turned. His README ships a matching six-frame sAnimCmd_Lance_Back[]
    # upstream, which was NOT harvested with the art -- if it is ever fetched,
    # a six-frame path is the better answer than this crop.
    "lance_back": ([0, 1, 2, 4, 5],
                   "6-frame yoshord sheet -> the 5-frame FRLG pattern; "
                   "frame 3 is a second arm-raise the Red anim has no slot for"),
}

# Back-pic donors that ship truecolour and need MORE than a lossless index.
# Keyed by file stem, so a NEW file can never be quantised by accident: the
# default path asserts the colour count and stops. Silently dropping colours to
# fit 4bpp produces plausible-looking corrupt art that is only caught by eye,
# which is the failure mode this project keeps re-learning.
QUANTISE = {
    # kwenio's Noland back pic (TAAR, staged 2026-07-29 from the 07-28 harvest).
    # Correct 64x256 geometry, but RGBA with 56 distinct opaque colours against
    # 4bpp's 16 -- and fully opaque, so the mint backdrop has to be masked to
    # index 0 by colour rather than by alpha or it renders as a solid green box
    # behind the player in battle. Chosen: mask everything within 8/255 per
    # channel of the corner pixel to index 0, MEDIANCUT the remaining 54 colours
    # to 15 with dithering OFF (a dither on a 64px sprite reads as noise).
    # Compared against the original as a decoded contact sheet before shipping:
    # hat, glove, vest and skin ramps all survive; the loss is one step of
    # shading on the forearm.
    "noland_back": "56-colour RGBA, opaque backdrop; mask bg by colour, "
                   "MEDIANCUT the rest to 15, no dither",
}

BG_TOLERANCE = 8  # per-channel, for masking a truecolour backdrop to index 0
PAL_TAG_BASE = 0x1200  # import_sprites used 0x1180..0x11DE; next tag up is 0x1800

slug = lambda s: re.sub(r"[^a-z0-9]+", "_", s.lower()).strip("_")


def key_of(disp):
    base = disp[:-len(" (anime)")] if disp.endswith(" (anime)") else disp
    return re.sub(r"[^A-Za-z0-9]+", "_", base).strip("_").upper()


def stem_of(disp):
    base = disp[:-len(" (anime)")] if disp.endswith(" (anime)") else disp
    return ALIAS.get(base, slug(base))


def display_names():
    """Character display names, in characters.txt order."""
    out = []
    with open(os.path.join(HERE, "characters.txt")) as f:
        for line in f:
            line = line.strip()
            if line and not line.startswith("#"):
                out.append(line.split("|")[0].strip())
    return out


