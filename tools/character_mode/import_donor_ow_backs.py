def bg_to_slot0(img, who):
    """Rotate the backdrop index to palette slot 0. Lossless, colours kept.

    ⚠️ `import_sprites.normalize_indexed()` only does this when a donor uses
    MORE than 16 slots; a donor that already fits 4bpp is returned untouched,
    backdrop wherever it happened to sit. The GBA renders sprite palette slot 0
    transparent whatever its colour value, so a donor whose backdrop sits at,
    say, slot 6 ships an opaque box round the sprite AND makes slot 6's real
    colour transparent instead. `taar/phoebe_back.png` is exactly that case, and
    it builds and links perfectly either way -- only an eye on the pixels tells
    the difference.
    """
    data = list(img.getdata())
    assert max(data) < 16, "%s: uses %d palette slots" % (who, max(data) + 1)
    bg = data[0]
    if bg == 0:
        img.info["transparency"] = 0
        return img
    pal = (img.getpalette() or [])[:48]
    pal += [0] * (48 - len(pal))
    order = [bg] + [i for i in range(16) if i != bg]
    remap = {old: new for new, old in enumerate(order)}
    newpal = []
    for old in order:
        newpal += pal[old * 3:old * 3 + 3]
    out = Image.new("P", img.size)
    out.putpalette(newpal + [0] * (768 - len(newpal)))
    out.putdata([remap[d] for d in data])
    out.info["transparency"] = 0
    return out


def build_player_sheet(pngs, fw, dst_png):
    """Write the (fw)x576 18-frame player-grade sheet the avatar animation needs.

    Donor strips are fw-wide frames on a 32px row in pokeemerald's own order:
    0 face S, 1 face N, 2 face W, 3/4 walk S, 5/6 walk N, 7/8 walk W. The player
    table wants 18: walk 0-8 then run 9-17.
    """
    imgs = []
    for p in pngs:
        im = normalize_indexed(Image.open(p))
        assert im.mode == "P", p
        imgs.append(bg_to_slot0(im, p))
    if len(imgs) == 2:                       # walk + run pair
        # ONE palette is written for the whole sheet, so a run strip indexed
        # against a different palette would come out recoloured -- and it would
        # still build, and still look like a sprite. Assert instead.
        assert imgs[0].getpalette()[:48] == imgs[1].getpalette()[:48], (
            "%s and %s do not share a palette; the run frames would be "
            "recoloured. Drop the run strip or re-index them together."
            % (pngs[0], pngs[1]))
        frames = slice_frames(imgs[0], fw)[:9] + slice_frames(imgs[1], fw)[:9]
        fmap = list(range(18))
    else:
        frames = slice_frames(imgs[0], fw)
        # 18 frames -> real walk+run; 9 -> the run block reuses the walk frames
        fmap = list(range(18)) if len(frames) >= 18 else WALK_MAP
    assert len(fmap) == NUM_PLAYER_FRAMES
    save_sheet(frames, fmap, imgs[0].getpalette(), 0, fw, dst_png)
    return imgs[0]


def build_back_pic(path, dst_png):
    """Write a 64x(64*n) back pic, backdrop at index 0. Returns (image, frames)."""
    base = os.path.basename(path)[:-len(".png")]
    img = Image.open(path)
    if img.mode == "P":
        img = bg_to_slot0(normalize_indexed(img), path)
    else:
        img = _quantise_truecolour(img, base, path)
    n = img.height // 64
    if base in BACK_FRAME_PICK:
        pick = BACK_FRAME_PICK[base][0]
        assert max(pick) < n, (path, n, pick)
    else:
        pick = list(range(n))
    assert len(pick) in (4, 5), (path, len(pick))
    out = Image.new("P", (64, 64 * len(pick)))
    out.putpalette(img.getpalette())
    for i, f in enumerate(pick):
        out.paste(img.crop((0, f * 64, 64, (f + 1) * 64)), (0, i * 64))
    out.info["transparency"] = 0
    out.save(dst_png, transparency=0)
    return out, len(pick)


def _quantise_truecolour(img, base, path):
    """Index a truecolour back pic, backdrop -> slot 0. Opt-in only."""
    rgb = img.convert("RGB")
    bg = rgb.getpixel((0, 0))
    fg = [max(abs(p[i] - bg[i]) for i in range(3)) > BG_TOLERANCE
          for p in rgb.getdata()]
    distinct = len({p for p, m in zip(rgb.getdata(), fg) if m})
    if distinct > 15 and base not in QUANTISE:
        raise SystemExit(
            "REFUSING TO GUESS -- %s has %d distinct non-backdrop colours and "
            "4bpp holds 15 (plus the backdrop at slot 0). Quantise it "
            "deliberately: add a QUANTISE entry naming the file and the choice "
            "made, after comparing the result against the original by eye."
            % (path, distinct))
    q = rgb.quantize(colors=15, method=Image.MEDIANCUT, dither=Image.Dither.NONE)
    pal = list(bg) + q.getpalette()[:45]
    out = Image.new("P", rgb.size)
    out.putpalette(pal + [0] * (768 - len(pal)))
    out.putdata([d + 1 if m else 0 for d, m in zip(q.getdata(), fg)])
    out.info["transparency"] = 0
    return out


