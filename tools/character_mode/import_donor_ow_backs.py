# donor discovery
# --------------------------------------------------------------------------
# A donor strip's FRAME WIDTH is not in its filename or its dimensions. 288x32
# is either 18 frames of 16 px or 9 frames of 32, and every 288-wide sheet in
# `sprites/donors/` is the latter -- so guessing 16 slices every sprite down the
# middle and pairs the halves as separate frames. THAT BUILDS, LINKS AND BOOTS;
# it was caught only by decoding the built .4bpp back out and looking at it.
#
# So the width is MEASURED. At a real frame boundary neither adjacent column
# carries much sprite, because frames are separated by the donor's own gutters.
# Measured over all 108 candidate strips in this tree: every 144-wide sheet
# scores 0-8 at fw=16, and every 288-wide sheet scores 19-21 at fw=16 and 0 at
# fw=32. The two clusters do not overlap and the threshold sits between them.
FRAME_BOUNDARY_MAX = 12


def _boundary_score(img, fw):
    """Worst internal frame boundary: min sprite pixels in the two columns."""
    w, h = img.size
    data = list(img.getdata())
    col = [sum(1 for y in range(h) if data[y * w + x]) for x in range(w)]
    return max(min(col[k * fw - 1], col[k * fw]) for k in range(1, w // fw))


def _checked_ow(path):
    """Open an overworld donor strip as (image, frame_width), or None.

    Matching is by EXACT filename, never a prefix, so `noland_ow_2.png` and
    `calem_ow_riding.png` (which has three blank frames where the walk cycle
    should be) can never be picked up as the walk sheet.
    """
    if not os.path.isfile(path):
        return None
    img = Image.open(path)
    if img.mode != "P" or img.height != 32:
        return None
    img = bg_to_slot0(normalize_indexed(img), path)
    for fw in (16, 32):
        if img.width % fw or img.width // fw not in (9, 18):
            continue
        if _boundary_score(img, fw) <= FRAME_BOUNDARY_MAX:
            return img, fw
    return None


def ow_candidates(disp):
    """[(src, [png, ...], fw, frames)] for this character, best source first.

    Two donor shapes are accepted, and nothing else:
      <stem>_ow_walking.png (+ <stem>_ow_running.png)  a real walk+run pair
      <stem>_ow.png                                    a 9- or 18-frame strip
    """
    stem = stem_of(disp)
    if not stem:
        return []
    out = []
    for src in PREFERENCE:
        d = os.path.join(DONORS, src)
        wpath = os.path.join(d, stem + "_ow_walking.png")
        walk = _checked_ow(wpath)
        if walk is not None and walk[0].width // walk[1] == 9:
            rpath = os.path.join(d, stem + "_ow_running.png")
            run = _checked_ow(rpath)
            if run is not None and run[1] == walk[1] and run[0].width // run[1] == 9:
                out.append((src, [wpath, rpath], walk[1], 18))
            else:
                out.append((src, [wpath], walk[1], 9))
            continue
        opath = os.path.join(d, stem + "_ow.png")
        one = _checked_ow(opath)
        if one is not None:
            out.append((src, [opath], one[1], one[0].width // one[1]))
    return out


def back_candidates(disp):
    """[(src, png, frames)] for this character, best source first."""
    stem = stem_of(disp)
    if not stem:
        return []
    out = []
    for src in PREFERENCE:
        p = os.path.join(DONORS, src, stem + "_back.png")
        if not os.path.isfile(p):
            continue
        img = Image.open(p)
        if img.width != 64 or img.height % 64:
            continue
        n = img.height // 64
        base = os.path.basename(p)[:-len(".png")]
        if n not in (4, 5) and base not in BACK_FRAME_PICK:
            continue
        out.append((src, p, len(BACK_FRAME_PICK[base][0])
                    if base in BACK_FRAME_PICK else n))
    return out


